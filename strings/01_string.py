# indexing
c = 'hello'
print(c[0])
print(c[2])
print(c[3])
print(c[4])
#negative indexing
d = 'kalu'
print(d[-1])
print(d[-2])
print(d[-3])
print(d[-4])
#slicing
m = 'hello guys'
print(m[0:6])
print(m[0:])
print(m[:6])
print(m[:])
print(m[2:6:2])
print(m[-1:-6:2])
print(m[-1:-6:-1])
print(m[::-1])
print(m[-1:-6:2])